// ── สุ่มแบบกำหนดได้ ──
const hash = (s) => { let h = 2166136261; for (const c of String(s)) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619) } return h >>> 0 }
const rng = (seed) => () => { seed |= 0; seed = (seed + 0x6D2B79F5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296 }

const BKK_MS = 7 * 3600 * 1000
/** เลขวันตามเวลาไทย (นับจาก 1970) */
export const marketDayNo = (ms = Date.now()) => Math.floor((ms + BKK_MS) / 86400000)
/** วันตั้งต้นของไทม์ไลน์เรื่อง — ⚠️ ห้ามเปลี่ยน ไม่งั้นข่าวทุกวันเปลี่ยนหมด */
export const EPOCH_DAY = marketDayNo(Date.UTC(2026, 10, 20, 17))   // 21 พ.ย. 2026 ไทย

// ไทม์ไลน์: เรื่องต่อเรื่องจาก EPOCH · cache ไว้ (เดินซ้ำทุกเรนเดอร์ไม่จำเป็น)
const plans = []   // [{ start, arc, crops }]
// น้ำหนัก = 1/√(เลเวลปลดล็อก) — Lv1 = 1 · Lv4 = .5 · Lv16 = .25 ⇒ พืชต้นออกบ่อยกว่าแต่ตัวท้ายยังมีโอกาส
const weighted = (list, u) => {
  const w = list.map(id => 1 / Math.sqrt(getCrop(id)?.unlockLevel || 1))
  let x = u * w.reduce((s, v) => s + v, 0)
  for (let i = 0; i < list.length; i++) { x -= w[i]; if (x < 0) return list[i] }
  return list[list.length - 1]
}
const RECENT = 10  // ต้องน้อยกว่าจำนวนเรื่องใน ARCS พอสมควร
function arcAt(k) {
  if (plans[k]) return plans[k]
  const start = k ? arcAt(k - 1).start + arcAt(k - 1).arc.steps.length : EPOCH_DAY
  const r = rng(hash('arc-' + k))
  // กันเรื่องซ้ำถี่: ไม่เอาเรื่องที่ออกไปใน RECENT เรื่องล่าสุด (ข่าวแล้งโผล่สองรอบในห้าวันดูแปลก)
  const recent = new Set()
  for (let j = Math.max(0, k - RECENT); j < k; j++) recent.add(arcAt(j).arc.id)
  const pool = ARCS.filter(x => !recent.has(x.id) && (x.since || 0) <= start)
  const arc = pool[Math.floor(r() * pool.length)]
  const aPool = arc.crops.a.filter(id => cropOk(id, start))
  const pick = (list) => (start >= SINCE_V2 ? weighted(list, r()) : list[Math.floor(r() * list.length)])
  const a = pick(aPool)
  const bPool = (arc.crops.b || []).filter(x => x !== a && cropOk(x, start))
  const b = bPool.length ? pick(bPool) : null
  return (plans[k] = { start, arc, crops: { a, b } })
}
function planOf(day) {
  if (day < EPOCH_DAY) day = EPOCH_DAY
  let k = 0
  while (arcAt(k).start + arcAt(k).arc.steps.length <= day) k++
  const p = arcAt(k)
  return { ...p, step: day - p.start }
}

/** id เรื่องของวันนั้น (เทสต์/ดีบัก) */
export const arcIdOf = (day) => planOf(day).arc.id

const fill = (s, crops, nameOf) => s.replaceAll('{a}', nameOf(crops.a)).replaceAll('{b}', crops.b ? nameOf(crops.b) : '')

/**
 * ข่าวตลาดของวัน
 * @param day     marketDayNo()
 * @param nameOf  (cropId) => ชื่อไทย (ส่ง getCrop มาจากฝั่งแอป — ไฟล์นี้ไม่ import crops กันวนกัน)
 * @returns {{ icon, head, body, short, boosts: [{id, pct}], tease, part, parts }}
 */
export function marketOf(day, nameOf) {
  const p = planOf(day)
  const s = p.arc.steps[p.step]
  let boosts = s.boost.map(([slot, pct]) => ({ id: p.crops[slot], pct })).filter(b => b.id)
  let short = null
  if (!boosts.length) {
    const r = rng(hash('short-' + day))
    const sh = SHORTS[Math.floor(r() * SHORTS.length)]
    const pool = ALL.filter(id => id !== p.crops.a && id !== p.crops.b && cropOk(id, day))
    const id = day >= SINCE_V2 ? weighted(pool, r()) : pool[Math.floor(r() * pool.length)]
    short = `${sh[0]} ${sh[1].replaceAll('{a}', nameOf(id))}`
    boosts = [{ id, pct: [30, 40, 50][Math.floor(r() * 3)] }]
  }
  const nx = planOf(day + 1)
  return {
    icon: s.icon, head: fill(s.head, p.crops, nameOf), body: fill(s.body, p.crops, nameOf), short, boosts,
    tease: fill(nx.arc.steps[nx.step].tease, nx.crops, nameOf),
    part: p.step + 1, parts: p.arc.steps.length,
  }
}

/** % ราคาขึ้นของพืชวันนี้ (0 = ปกติ) */
export function boostPct(cropId, market) {
  return market?.boosts?.find(b => b.id === cropId)?.pct || 0
}
/** ราคาขายจริงวันนี้ */
export const boosted = (price, pct) => Math.round(price * (1 + (pct || 0) / 100))

/** ข้อความโพสต์กระดานรุ่น ≤ 140 ตัว (rules บังคับ) */
export function newsMsg(m, nameOf) {
  const up = m.boosts.map(b => `${nameOf(b.id)} +${b.pct}%`).join(' · ')
  let msg = `ข่าวตลาดสมุนไพร: ${m.head} · ราคาวันนี้ ${up}`
  if (msg.length > 140) msg = msg.slice(0, 139) + '…'
  return msg
}
