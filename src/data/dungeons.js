/** ทีมศัตรูของด่าน → รูปแบบเดียวกับทีมเพ็ทที่เอนจินรับ */
export function waveTeam(w) {
  return w.team.map(id => {
    const m = getMonster(id)
    return { id, rarity: m.rarity, element: m.element, grade: w.grade, ...(w.boost !== 1 ? { boost: w.boost } : {}) }
  })
}
