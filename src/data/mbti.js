const BY_CODE = new Map(MBTI_TYPES.map(t => [t.code, t]))
/** 'enfj' / 'ENFJ' → { code, name, group, groupLabel, color } หรือ null */
export function mbtiOf(v) {
  const t = typeof v === 'string' ? BY_CODE.get(v.toUpperCase()) : null
  return t ? { ...t, groupLabel: MBTI_GROUPS[t.group].label, color: MBTI_GROUPS[t.group].color } : null
}

